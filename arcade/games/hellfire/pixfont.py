GLYPH = {k: np.array([c == "#" for c in v[:35]], dtype=bool).reshape(7, 5) for k, v in _GLYPHS.items()}

# shading from the top row to the bottom row of a glyph
STYLES = {
    "red": [ramp("red", t) for t in (0.0, 0.08, 0.16, 0.24, 0.32, 0.42, 0.52)],
    "grey": [ramp("grey", t) for t in (0.0, 0.06, 0.12, 0.2, 0.28, 0.36, 0.44)],
    "gold": [ramp("fire", t) for t in (0.08, 0.12, 0.18, 0.24, 0.3, 0.38, 0.46)],
    "green": [ramp("green", t) for t in (0.0, 0.05, 0.1, 0.15, 0.2, 0.26, 0.32)],
    "white": [ramp("grey", 0.0)] * 7,
}
SHADOW = ramp("grey", 0.97)


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * 6 * scale - scale if text else 0


def draw_text(frame: np.ndarray, text: str, x: int, y: int, style: str = "red", scale: int = 1,
              shadow: bool = True) -> int:
    """Draw ``text`` (upper-cased) with its top-left at (x, y); returns the width drawn."""
    shades = STYLES.get(style, STYLES["red"])
    h, w = frame.shape[:2]
    cx = x
    for ch in text.upper():
        g = GLYPH.get(ch, GLYPH["?"])
        if ch != " ":
            gs = np.repeat(np.repeat(g, scale, axis=0), scale, axis=1)
            col = np.repeat(np.array(shades, dtype=np.uint8), scale)[:, None]
            for dx, dy, colour in (((scale + 1) // 2, (scale + 1) // 2, None), (0, 0, col)) if shadow \
                    else ((0, 0, col),):
                x0, y0 = cx + dx, y + dy
                x1, y1 = x0 + gs.shape[1], y0 + gs.shape[0]
                if x1 <= 0 or y1 <= 0 or x0 >= w or y0 >= h:
                    continue
                sx0, sy0 = max(0, -x0), max(0, -y0)
                sx1, sy1 = gs.shape[1] - max(0, x1 - w), gs.shape[0] - max(0, y1 - h)
                m = gs[sy0:sy1, sx0:sx1]
                region = frame[y0 + sy0:y0 + sy1, x0 + sx0:x0 + sx1]
                if colour is None:
                    region[m] = SHADOW
                else:
                    region[m] = np.broadcast_to(colour[sy0:sy1], m.shape)[m]
        cx += 6 * scale
    return cx - x


def draw_text_centered(frame: np.ndarray, text: str, y: int, style: str = "red", scale: int = 1,
                       cx: int | None = None) -> None:
    w = frame.shape[1]
    centre = w // 2 if cx is None else cx
    draw_text(frame, text, centre - text_width(text, scale) // 2, y, style, scale)
